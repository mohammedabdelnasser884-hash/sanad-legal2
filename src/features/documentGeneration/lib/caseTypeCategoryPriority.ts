import { DOCUMENT_CATEGORIES } from '../hooks/useDocumentTemplates';

type DocumentCategory = (typeof DOCUMENT_CATEGORIES)[number];

interface CaseTypeRule {
  /** substrings (بعد trim، مطابقة includes بسيطة) — لو أي واحدة اتلاقت في case_type يتطبّق الترتيب ده */
  keywords: string[];
  /** التصنيفات الأكتر صلة، الأعلى صلة أول القايمة */
  priority: DocumentCategory[];
}

// مسودة أولية — محتاجة مراجعتك وتصحيحك (راجع التحذير فوق).
const RULES: CaseTypeRule[] = [
  {
    keywords: ['نفقة', 'طلاق', 'خلع', 'حضانة', 'رؤية', 'أحوال شخصية', 'أسرة'],
    priority: ['عرائض', 'إعلانات', 'توكيلات'],
  },
  {
    keywords: ['عمالي', 'عمل', 'فصل تعسفي'],
    priority: ['عرائض', 'تظلمات', 'طلبات'],
  },
  {
    keywords: ['تجاري', 'شركات', 'إفلاس'],
    priority: ['عقود', 'إنذارات', 'عرائض'],
  },
  {
    keywords: ['إيجار', 'عقاري', 'طرد للغصب'],
    priority: ['عقود', 'إنذارات', 'عرائض'],
  },
  {
    keywords: ['جنائي', 'جنحة', 'جنح', 'جناية'],
    priority: ['جنح مباشرة', 'عرائض', 'طلبات'],
  },
  {
    keywords: ['إداري', 'مجلس الدولة'],
    priority: ['تظلمات', 'طلبات', 'عرائض'],
  },
  {
    keywords: ['مدني'],
    priority: ['عرائض', 'إنذارات', 'طلبات'],
  },
];

/**
 * بيرجّع ترتيب أولوية التصنيفات لنوع قضية معيّن (أعلى صلة الأول)،
 * أو array فاضية لو case_type فاضي أو مفيش قاعدة مطابقة (يبقى الترتيب
 * الافتراضي الموجود زي ما هو من غير أي تغيير — القسم 5.1: "مش يخفي
 * الباقي").
 */
export function getCategoryPriorityForCaseType(caseType: string | null | undefined): DocumentCategory[] {
  const norm = (caseType ?? '').trim();
  if (norm === '') return [];
  const rule = RULES.find((r) => r.keywords.some((k) => norm.includes(k)));
  return rule?.priority ?? [];
}
