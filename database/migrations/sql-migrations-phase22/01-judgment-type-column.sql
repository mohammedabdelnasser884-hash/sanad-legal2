-- جزء من تنفيذ البنود 14-18 (إعادة تصميم مودال "النطق بالحكم"،
-- 12 سبتمبر 2026): بيميّز نوع الحكم المسجَّل على الجلسة — بدل الاكتفاء
-- بتخزين النص في `result` بس. الهدف: إمكانية عمل تقارير/فلاتر بعدين
-- ("كل الأحكام التمهيدية في القضية")، وإظهار بادچ مميز ("⚖️ حكم تمهيدي")
-- على الجلسة في التايم لاين بدل "📌 النتيجة" العادية (TimelineSection.tsx).
--
-- القيم المتوقعة (بيتم فرضها من كود التطبيق، مش CHECK constraint —
-- نفس نمط أعمدة نصية حرة تانية في الجدول ده): 'نهائي' | 'تمهيدي' | NULL.
-- NULL = مفيش حكم متسجّل على الجلسة دي (الوضع الافتراضي لكل الجلسات
-- الحالية والجديدة العادية).
--
-- بسيطة، بلا كسر لأي بيانات قائمة (كل الصفوف الحالية هتاخد NULL تلقائي —
-- بما فيها أي حكم نهائي اتسجّل قبل المايجريشن ده، لأنه كان بيستخدم بس
-- result + is_judgment_reserved من غير أي تمييز نوع. مفيش داعي لأي
-- backfill: الأحكام النهائية القديمة هتفضل من غير judgment_type، وده
-- سلوك مقبول لأنها أصلاً بتتعرف من showJudgmentCard (is_judgment_reserved
-- + caseStatus === 'منتهية') مش من العمود الجديد).
-- الملف Idempotent (IF NOT EXISTS)، آمن يتشغل أكتر من مرة.
-- ══════════════════════════════════════════════════════════════════

ALTER TABLE case_sessions
  ADD COLUMN IF NOT EXISTS judgment_type text DEFAULT NULL;

COMMENT ON COLUMN case_sessions.judgment_type IS
  'نوع الحكم المسجَّل على هذه الجلسة: نهائي / تمهيدي / NULL (مفيش حكم). يُكتب من FinalJudgmentModal.tsx وقت تسجيل الحكم — نهائي عن طريق مسار "حكم نهائي"، تمهيدي عن طريق مسار "حكم تمهيدي/جزئي". مستقل عن is_judgment_reserved (اللي بيتحكم في ظهور زرار "🏛️ النطق بالحكم" بس).';
