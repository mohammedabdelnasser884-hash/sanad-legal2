-- الخلفية: 13-security-definer-write-lock.sql (G2) ضاف استثناء صريح
-- لمسار "office/<tenant_id>/logo.ext" عشان مايضيفش رفض جديد فوق
-- مشكلة قائمة كانت لسه محتاجة تأكيد. اتأكدت فعليًا (9 سبتمبر 2026):
-- الأدمن العادي كان فعلاً مش قادر يرفع شعار المكتب خالص — مش بسبب
-- الدالة دي، لكن بسبب سياسة phase2/02 الأساسية (tenant_scoped_case_
-- client_docs_insert) اللي بترفض أي مسار مش بادئ بـtenant_id مباشرة.
--
-- الإصلاح الفعلي كان في الكود (useAdminOffice.ts): تغيير مسار الرفع
-- من office/<tenant_id>/logo.ext لـ <tenant_id>/office-logo.ext —
-- نفس نمط كل باقي الملفات في النظام، فبيعدي من سياسة phase2/02
-- الموجودة أصلاً من غير أي تعديل عليها.
--
-- اتأكد كمان (9 سبتمبر 2026) إن مفيش أي مكتب عنده شعار محفوظ فعليًا
-- على الإنتاج بالمسار القديم — فمفيش أي بيانات محتاجة ترحيل، والاستثناء
-- في الدالة دي بقى كود ميت (مش هيتحقق تاني أبدًا بعد إصلاح الكود).
-- الملف ده بيشيله بس للنظافة ولمنع أي لبس مستقبلي — صفر تغيير سلوك
-- فعلي على الإنتاج (المسار القديم مش هيتكتب تاني خالص).
-- ============================================================

CREATE OR REPLACE FUNCTION public.storage_object_write_allowed(p_name text)
RETURNS boolean
LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public
AS $$
DECLARE
  v_first  text := (storage.foldername(p_name))[1];
  v_tenant uuid;
BEGIN
  -- المسار الوحيد المتعارف عليه دلوقتي: <tenant_id>/اسم-الملف
  -- (مستندات قضايا/عملاء/أرشيف/شعار المكتب — كلهم بنفس النمط بعد
  -- إصلاح مسار الشعار في الكود)
  BEGIN
    v_tenant := v_first::uuid;
  EXCEPTION WHEN invalid_text_representation THEN
    v_tenant := NULL;
  END;

  IF v_tenant IS NULL THEN
    RETURN false; -- مسار مش متعارف عليه — امنع افتراضيًا
  END IF;

  RETURN public.tenant_write_allowed(v_tenant);
END;
$$;

