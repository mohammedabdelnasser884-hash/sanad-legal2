-- ============================================================
-- 15-15 (فيكس D4 — اكتُشف أثناء اختبار 10 اليدوي، 10 سبتمبر 2026)
-- عمود previous_plan على tenant_subscription_payments
-- ============================================================
-- اختبار 10 (تراجع عن تأكيد دفع) كشف إن "تراجع" كانت بترجّع
-- subscription_due_at بس، وتسيب subscription_plan زي ما هي — فبعد
-- التراجع عن ترقية، المكتب كان بيفضل على الباقة الجديدة (الأعلى) لكن
-- بموعد استحقاق زي لو لسه على الباقة القديمة، وده تضارب حقيقي
-- (المكتب بياخد مميزات باقة مدفوعها أقل من اللي فعليًا مدفوع).
--
-- بنفس نمط previous_due_at (ميجريشن 10) بالظبط: نسجّل الباقة "قبل"
-- كل تأكيد دفع، عشان "تراجع" يقدر يرجّعها صح جنب الموعد.
--
-- ALTER ADD COLUMN IF NOT EXISTS — آمن للتشغيل على الإنتاج فورًا.
-- الصفوف الموجودة فعلاً (لو فيه) هتفضل previous_plan فيها NULL —
-- يعني لو حد عمل "تراجع" على دفعة قديمة اتسجلت قبل الفيكس ده، الباقة
-- مش هترجع (نفس السلوك القديم بالظبط لحد ما يتعمل تأكيد دفع جديد بعد
-- الفيكس)، لكن الموعد (previous_due_at) هيفضل بيرجع صح زي الأول —
-- مفيش أي كسر لسلوك موجود.
-- ============================================================

ALTER TABLE public.tenant_subscription_payments
  ADD COLUMN IF NOT EXISTS previous_plan text;

COMMENT ON COLUMN public.tenant_subscription_payments.previous_plan IS
  'قيمة tenants.subscription_plan قبل هذا التأكيد مباشرة (NULL لو كان المكتب تجربة/أول دفعة). تُستخدم في D4 (تراجع عن آخر تأكيد دفع) لإرجاع الباقة صح جنب الموعد، بنفس منطق previous_due_at.';
