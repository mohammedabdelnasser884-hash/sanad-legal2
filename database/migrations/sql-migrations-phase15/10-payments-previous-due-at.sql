-- ============================================================
-- 15-10 (تمهيد لـ D1 + D4) — عمود previous_due_at على tenant_subscription_payments
-- ============================================================
-- D4 ("تراجع عن آخر تأكيد دفع") محتاج يرجّع tenants.subscription_due_at
-- بالظبط للقيمة اللي كانت قبل التأكيد ده. period_start مش دايمًا نفس
-- القيمة دي (في حالة الترقية، period_start = تاريخ الترقية نفسه مش
-- الميعاد القديم)، فبنضيف عمود مخصص يسجّل القيمة القديمة كما هي وقت
-- كل تأكيد دفع — بغض النظر عن نوع العملية (تجديد عادي/ترقية/أول دفعة
-- من تجربة).
--
-- ALTER ADD COLUMN IF NOT EXISTS — آمن للتشغيل على الإنتاج فورًا،
-- مفيش أي تأثير على صفوف موجودة (الجدول لسه فاضي، مفيش أي actions
-- بتكتب فيه لحد دلوقتي D1 لسه لم يبدأ).
-- ============================================================

ALTER TABLE public.tenant_subscription_payments
  ADD COLUMN IF NOT EXISTS previous_due_at timestamptz;

COMMENT ON COLUMN public.tenant_subscription_payments.previous_due_at IS
  'قيمة tenants.subscription_due_at قبل هذا التأكيد مباشرة (NULL لو كان المكتب تجربة/أول دفعة). تُستخدم في D4 (تراجع عن آخر تأكيد دفع) لإرجاع القيمة الدقيقة.';
