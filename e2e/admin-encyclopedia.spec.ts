import { test, expect } from '@playwright/test';
import { login } from './utils';

// مرحلة 4 (تصفح/تحميل لكل المستخدمين) — نفس نمط admin-legal-library.spec.ts
// بالظبط: قسم إدارة "الموسوعة القانونية" مقصور بالكامل على حساب السوبر
// أدمن الوحيد (SUPER_ADMIN_EMAIL في AdminPanel.tsx). حساب E2E_TEST_EMAIL
// هو owner/admin لمكتب تجريبي عادي (مش سوبر أدمن)، فالتست ده بيتأكد إن
// القسم مش ظاهر له خالص في لوحة الإدارة.
//
// ⚠️ تحديث (فصل إدارة الموسوعة عن شبكة أقسام لوحة الإدارة — طلب Gemy):
// كرت "الموسوعة القانونية" اتشال بالكامل من شبكة أقسام لوحة الإدارة —
// دلوقتي مش موجود فيها لأي حساب خالص (ولا حتى السوبر أدمن)، لأن القسم
// بقى بيتفتح بس عن طريق زرار "إدارة الموسوعة" (encyclopedia-manage-button)
// الظاهر في صفحة الموسوعة العادية لحساب السوبر أدمن بس — مغطى (غيابه
// لغير السوبر أدمن) في encyclopedia-browse.spec.ts. التست ده بالتالي لسه
// صحيح زي ما هو (admin-section-encyclopedia مالوش وجود في الشبكة أصلًا
// لأي حد)، لكن بقى بيتأكد من غياب الكرت نفسه مش بس غيابه عن حساب معيّن.
//
// ⚠️ شرط أساسي: حساب E2E_TEST_EMAIL لازم يكون Admin/Owner، وإلا
// desktop-nav-admin مش هيظهر أصلًا (نفس ملحوظة admin-archive-lifecycle.spec.ts).
//
// ⚠️ ملحوظة مهمة (تختلف عن legal_library): قسم *إدارة* الموسوعة (ده
// التست) مقصور على سوبر أدمن، لكن تاب *تصفح/تحميل* الموسوعة الجديد
// (نفس التسمية في القائمة الجانبية، لكن خارج لوحة الإدارة) متاح لكل
// المستخدمين بلا استثناء — مغطى في encyclopedia-browse.spec.ts المنفصل.

test('حساب مكتب عادي (مش سوبر أدمن) → كرت قسم "الموسوعة القانونية" مش ظاهر في شبكة أقسام لوحة الإدارة (اتشال بالكامل)', async ({ page }) => {
  await login(page);
  await page.getByTestId('desktop-nav-admin').click();

  await expect(page.getByTestId('admin-section-encyclopedia')).toHaveCount(0);
});
