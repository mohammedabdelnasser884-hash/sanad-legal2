-- ============================================================
-- 15-03 (A4) — تعبئة subscription_due_at للمكاتب الشغالة حاليًا
-- ============================================================
-- المكاتب دي لسه مدفوعة برّه النظام (نقدي/فودافون كاش من غير أي
-- تسجيل داخلي) — مفيش تاريخ تجديد حقيقي مسجّل لأي مكتب منها.
-- القرار المتفق عليه: كل مكتب ياخد ميعاد تجديد أول موحّد = شهر من
-- تاريخ تفعيل النظام ده (نفس اليوم لكل المكاتب)، بدل ما نطلب من
-- جيمي يدخل تاريخ كل مكتب الحقيقي يدويًا.
--
-- ينطبق على المكاتب "المدفوعة" بس (status='active') — التجربة
-- (status='trial') بتستخدم trial_ends_at الموجود بالفعل، مش
-- subscription_due_at. مكتب موقوف (suspended) هياخد قيمة كمان
-- (مش هتفرق طول ما هو موقوف، لكن تفضل جاهزة لو اتفعّل تاني).
-- ============================================================

UPDATE public.tenants
   SET subscription_due_at = now() + interval '1 month'
 WHERE subscription_due_at IS NULL
   AND status IS DISTINCT FROM 'trial';
